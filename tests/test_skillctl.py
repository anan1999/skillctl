import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

from skillctl import Manager, fingerprint, replace_directory


class ManagerTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.source = self.root/'source'; self.source.mkdir()
        (self.source/'catalog.json').write_text(json.dumps({'schema':1,'skills':['example-skill']}))
        self.skill = self.source/'skills/example-skill'; self.skill.mkdir(parents=True)
        (self.skill/'SKILL.md').write_text('---\nname: example-skill\ndescription: Example testing skill.\n---\nBody\n')
        self.target = self.root/'target'; self.state = self.root/'state'
        self.m = Manager(self.source,self.target,self.state)

    def test_install_update_rollback_restores_bytes_and_receipt(self):
        self.m.install('example-skill'); original = fingerprint(self.target/'example-skill')
        (self.skill/'data.txt').write_text('version 2')
        self.assertEqual('update-available',self.m.listing()[0]['status'])
        self.m.install('example-skill')
        self.m.rollback('example-skill')
        self.assertEqual(original,fingerprint(self.target/'example-skill'))
        self.assertEqual(original,self.m.db()['installed']['example-skill']['files'])
        self.m.rollback('example-skill')
        self.assertFalse((self.target/'example-skill').exists())

    def test_local_edits_block_install_and_rollback(self):
        self.m.install('example-skill')
        (self.target/'example-skill/user.txt').write_text('keep')
        for operation in [self.m.install,self.m.rollback]:
            with self.assertRaisesRegex(ValueError,'Local drift'):operation('example-skill')
        self.assertEqual('keep',(self.target/'example-skill/user.txt').read_text())

    def test_python_cache_does_not_ship_or_create_false_drift(self):
        cache = self.skill/'scripts/__pycache__'
        cache.mkdir(parents=True)
        (cache/'helper.cpython-311.pyc').write_bytes(b'generated')
        (self.skill/'scripts/helper.py').write_text('VALUE = 1\n')
        self.m.install('example-skill')
        installed = self.target/'example-skill'
        self.assertFalse((installed/'scripts/__pycache__').exists())
        runtime_cache = installed/'scripts/__pycache__'
        runtime_cache.mkdir()
        (runtime_cache/'helper.cpython-311.pyc').write_bytes(b'generated by invocation')
        self.assertEqual('current', self.m.listing()[0]['status'])
        (installed/'scripts/helper.py').write_text('VALUE = 2\n')
        self.assertEqual('local-drift', self.m.listing()[0]['status'])
        with self.assertRaisesRegex(ValueError, 'Local drift'):
            self.m.install('example-skill')

    def test_adopt_requires_identical_and_leaves_other_skills(self):
        import shutil
        shutil.copytree(self.skill,self.target/'example-skill')
        other = self.target/'system-plugin';other.mkdir();(other/'keep').write_text('safe')
        with self.assertRaisesRegex(ValueError,'Unmanaged'):self.m.install('example-skill')
        self.m.install('example-skill',adopt=True)
        self.m.rollback('example-skill')
        self.assertEqual('unmanaged-identical',self.m.listing()[0]['status'])
        self.assertEqual('safe',(other/'keep').read_text())

    def test_conflicting_unmanaged_is_never_overwritten(self):
        destination=self.target/'example-skill';destination.mkdir(parents=True)
        (destination/'SKILL.md').write_text('user version')
        with self.assertRaisesRegex(ValueError,'Unmanaged'):self.m.install('example-skill',adopt=True)

    def test_unknown_and_traversal_names_rejected(self):
        with self.assertRaises(ValueError):self.m.install('../system')
        (self.source/'catalog.json').write_text(json.dumps({'schema':1,'skills':['../system']}))
        with self.assertRaises(ValueError):Manager(self.source,self.target,self.state)

    def test_broken_reference_rejected(self):
        with (self.skill/'SKILL.md').open('a') as f:f.write('[details](references/missing.md)')
        with self.assertRaisesRegex(ValueError,'Broken local link'):self.m.install('example-skill')

    def test_fenced_template_links_are_not_package_dependencies(self):
        template = self.skill/'template.md'
        template.write_text('````markdown\n[model](./onnx/model.onnx)\n'
                            '```sh\nexample command\n```\n````\n')
        self.m.install('example-skill')
        with template.open('a') as f:
            f.write('[actual reference](missing.md)\n')
        with self.assertRaisesRegex(ValueError, 'Broken local link'):
            self.m.install('example-skill')

    def test_tampered_snapshot_blocks_rollback(self):
        self.m.install('example-skill');(self.skill/'v2').write_text('new');self.m.install('example-skill')
        backup=Path(self.m.db()['history']['example-skill'][-1]['backup'])
        (backup/'tampered').write_text('bad')
        with self.assertRaisesRegex(ValueError,'snapshot'):self.m.rollback('example-skill')

    def test_state_write_failure_compensates_install(self):
        self.m.install('example-skill');before=fingerprint(self.target/'example-skill')
        (self.skill/'v2').write_text('new')
        import skillctl
        real=skillctl.write_json
        def failing(path,value):
            if path==self.m.db_path:raise OSError('disk failure')
            return real(path,value)
        with patch('skillctl.write_json',side_effect=failing):
            with self.assertRaises(OSError):self.m.install('example-skill')
        self.assertEqual(before,fingerprint(self.target/'example-skill'))
        self.assertEqual(before,self.m.db()['installed']['example-skill']['files'])

    def test_rename_failure_preserves_previous_directory(self):
        self.m.install('example-skill');before=fingerprint(self.target/'example-skill')
        import os
        real=os.replace
        def fail(source,dest):
            if '-stage-' in str(source):raise OSError('rename failure')
            return real(source,dest)
        with patch('skillctl.os.replace',side_effect=fail):
            with self.assertRaises(OSError):replace_directory(self.target/'example-skill',self.skill)
        self.assertEqual(before,fingerprint(self.target/'example-skill'))

    def test_lock_prevents_concurrent_mutation(self):
        with self.m.lock():
            with self.assertRaisesRegex(ValueError,'lock'):self.m.install('example-skill')

    def test_target_registries_are_separate(self):
        other=Manager(self.source,self.root/'another-target',self.state)
        self.assertNotEqual(other.state,self.m.state)
        self.m.install('example-skill')
        self.assertEqual({},other.db()['installed'])


if __name__=='__main__':unittest.main()
