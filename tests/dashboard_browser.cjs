const {chromium} = require(process.env.SKILLCTL_PLAYWRIGHT || 'playwright');
const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const info = JSON.parse(fs.readFileSync(process.argv[2],'utf8'));
assert.equal(info.fixture, true, 'Use a fresh dashboard_demo.py fixture');
assert(path.basename(info.root).startsWith('skillctl-dashboard-demo-'));
const artifacts = path.resolve('.demo/dashboard-ui'); fs.mkdirSync(artifacts,{recursive:true});
const note = name => path.join(info.root,'project/.pi/skills',name,'notes.txt');
