  assert.equal(await page.locator('#rows img').count(),0);
  await page.locator('#target').selectOption('1');assert.equal(await page.locator('#rows tr').count(),5);
  await select('merge-demo');assert(await page.locator('#merge').isDisabled());
  await page.locator('#target').selectOption('0');
  await select('adopt-demo');const original=read(note('adopt-demo'));
  assert((await page.locator('#diffs').innerText()).includes('<img'));
  assert.equal(await page.locator('#diffs img').count(),0);
  await preview('預覽接管');assert.equal(read(note('adopt-demo')),original);assert(await page.locator('#apply').isEnabled());
  await apply();assert((await page.locator('#notice').innerText()).includes('接管完成'));assert.equal(read(note('adopt-demo')),original);
  await select('merge-demo');const before=read(note('merge-demo'));
  await preview('預覽合併更新');assert.equal(read(note('merge-demo')),before);assert((await page.locator('#plan-changes').innerText()).includes('UPSTREAM'));
  await page.screenshot({path:path.join(artifacts,'dashboard-merge-preview.png'),fullPage:true});
  await apply();assert(read(note('merge-demo')).includes('LOCAL'));assert(read(note('merge-demo')).includes('UPSTREAM'));
  await select('conflict-demo');const conflict=read(note('conflict-demo'));
  await preview('預覽合併更新');assert(await page.locator('#apply').isDisabled());assert((await page.locator('#plan-changes').innerText()).includes('<<<<<<< LOCAL'));
  await page.screenshot({path:path.join(artifacts,'dashboard-conflict.png'),fullPage:true});
  await preview('預覽保留本機');assert(await page.locator('#apply').isEnabled());await apply();assert.equal(read(note('conflict-demo')),conflict);
  await select('stale-demo');await preview('預覽保留本機');
  fs.appendFileSync(note('stale-demo'),'EDIT AFTER PREVIEW\n');
  await apply();assert((await page.locator('#notice').innerText()).includes('stale'));assert(await page.locator('#apply').isDisabled());assert(read(note('stale-demo')).includes('EDIT AFTER PREVIEW'));
  await preview('預覽保留本機');await page.locator('#cancel').click();assert(await page.locator('#preview').isHidden());
